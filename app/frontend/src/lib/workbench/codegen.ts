import { analyzeGraph, definition, type Graph } from './graph';

export function generatePython(graph: Graph): { code: string; lineNodes: (string | null)[] } {
  const result = analyzeGraph(graph);
  if (result.errors.length) throw new Error(result.errors[0].message);
  const lines: string[] = [], lineNodes: (string | null)[] = [];
  const add = (text: string, id: string | null = null) => { for (const line of text.split('\n')) { lines.push(line); lineNodes.push(id); } };
  add('# Generated by UMCode visual builder. Randomly initialized architecture.\nimport torch\nfrom torch import nn\n\n');
  if (graph.nodes.some(n => n.kind === 'attention' || n.kind === 'transformer')) add(`class SelfAttention(nn.Module):
    def __init__(self, width, heads, dropout, causal=True):
        super().__init__()
        self.causal = causal
        self.attention = nn.MultiheadAttention(width, heads, dropout=dropout, batch_first=True)

    def forward(self, x):
        mask = torch.ones(x.size(1), x.size(1), device=x.device, dtype=torch.bool).triu(1) if self.causal else None
        return self.attention(x, x, x, attn_mask=mask, need_weights=False)[0]
\n`);
  if (graph.nodes.some(n => n.kind === 'transformer')) add(`class TransformerBlock(nn.Module):
    def __init__(self, width, heads, expansion, dropout, causal=True):
        super().__init__()
        self.norm1 = nn.LayerNorm(width)
        self.attention = SelfAttention(width, heads, dropout, causal)
        self.norm2 = nn.LayerNorm(width)
        self.mlp = nn.Sequential(nn.Linear(width, width * expansion), nn.GELU(), nn.Linear(width * expansion, width), nn.Dropout(dropout))

    def forward(self, x):
        x = x + self.attention(self.norm1(x))
        return x + self.mlp(self.norm2(x))
\n`);
  if (graph.nodes.some(n => n.kind === 'position')) add(`class PositionEmbedding(nn.Module):
    def __init__(self, length, width):
        super().__init__()
        self.embedding = nn.Embedding(length, width)

    def forward(self, x):
        return x + self.embedding(torch.arange(x.size(1), device=x.device)).unsqueeze(0)
\n`);
  if (graph.nodes.some(n => n.kind === 'meanpool')) add(`class MeanPool(nn.Module):
    def forward(self, x):
        return x.mean(dim=1)
\n`);
  if (graph.nodes.some(n => n.kind === 'patchembedding')) add(`class PatchEmbedding(nn.Module):
    def __init__(self, channels, width, patch):
        super().__init__()
        self.projection = nn.Conv2d(channels, width, kernel_size=patch, stride=patch)

    def forward(self, x):
        return self.projection(x).flatten(2).transpose(1, 2)
\n`);
  add('class Model(nn.Module):\n    def __init__(self):\n        super().__init__()\n        self.layers = nn.ModuleDict()');
  const ids = new Map(result.order.map((node, i) => [node.id, `layer_${i}`]));
  for (const node of result.order) {
    if (node.kind === 'input' || node.kind === 'output') continue;
    const c = node.config, key = ids.get(node.id)!;
    const source = graph.edges.find(e => e.target === node.id)!.source;
    const width = result.shapes[source].dims.at(-1);
    let expression: string;
    switch (node.kind) {
      case 'embedding': expression = `nn.Embedding(${c.vocab}, ${c.width})`; break;
      case 'position': expression = `PositionEmbedding(${c.length}, ${width})`; break;
      case 'linear': expression = `nn.Linear(${width}, ${c.outFeatures}, bias=${c.bias ? 'True' : 'False'})`; break;
      case 'attention': expression = `SelfAttention(${width}, ${c.heads}, ${c.dropout}, ${c.causal === false ? 'False' : 'True'})`; break;
      case 'transformer': expression = `nn.Sequential(*[TransformerBlock(${width}, ${c.heads}, ${c.expansion}, ${c.dropout}, ${c.causal === false ? 'False' : 'True'}) for _ in range(${c.repeat})])`; break;
      case 'layernorm': expression = `nn.LayerNorm(${width})`; break;
      case 'dropout': expression = `nn.Dropout(${c.dropout})`; break;
      case 'meanpool': expression = 'MeanPool()'; break;
      case 'gelu': expression = 'nn.GELU()'; break;
      case 'relu': expression = 'nn.ReLU()'; break;
      case 'conv2d': expression = `nn.Conv2d(${result.shapes[source].dims[1]}, ${c.channels}, kernel_size=${c.kernel}, stride=${c.stride}, padding=${c.padding}, bias=${c.bias ? 'True' : 'False'})`; break;
      case 'batchnorm2d': expression = `nn.BatchNorm2d(${result.shapes[source].dims[1]})`; break;
      case 'maxpool2d': expression = `nn.MaxPool2d(kernel_size=${c.kernel}, stride=${c.stride}, padding=${c.padding})`; break;
      case 'avgpool2d': expression = `nn.AvgPool2d(kernel_size=${c.kernel}, stride=${c.stride}, padding=${c.padding})`; break;
      case 'globalpool2d': expression = 'nn.Sequential(nn.AdaptiveAvgPool2d(1), nn.Flatten(1))'; break;
      case 'flatten': expression = 'nn.Flatten(start_dim=1)'; break;
      case 'patchembedding': expression = `PatchEmbedding(${result.shapes[source].dims[1]}, ${c.width}, ${c.patch})`; break;
    }
    add(`        # ${definition(node.kind).name}\n        self.layers["${key}"] = ${expression!}`, node.id);
  }
  for (const node of result.order.filter(n => n.kind === 'linear' && n.config.tieEmbedding)) {
    const embedding = result.order.find(n => n.kind === 'embedding')!;
    add(`        self.layers["${ids.get(node.id)}"].weight = self.layers["${ids.get(embedding.id)}"].weight`, node.id);
  }
  add('\n    def forward(self, x):');
  for (const node of result.order) if (node.kind !== 'input' && node.kind !== 'output') add(`        x = self.layers["${ids.get(node.id)}"](x)`, node.id);
  add('        return x\n');
  return { code: lines.join('\n'), lineNodes };
}
